// Generates SEO diagram images for the pages in /content.
// Usage: node scripts/content-images/generate.mjs [page-slug ...]
// Output: public/images/<slug>/<file>.webp (+ optional .svg) and content/<dir>/10-images.md
import sharp from "sharp";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../..",
);
const pageFiles = (
  await fs.readdir(
    path.join(path.dirname(fileURLToPath(import.meta.url)), "pages"),
  )
).filter((f) => f.endsWith(".mjs"));
const only = process.argv.slice(2);

for (const pf of pageFiles) {
  const page = (await import(`./pages/${pf}`)).default;
  if (only.length && !only.includes(page.slug)) continue;
  const outDir = path.join(root, "public", "images", page.slug);
  await fs.mkdir(outDir, { recursive: true });
  const rows = [];
  for (const img of page.images) {
    const svg = img.svg();
    const base = img.file.replace(/\.(webp|svg)$/, "");
    const w = img.w ?? (img.og ? 1200 : 1600),
      h = img.h ?? (img.og ? 630 : 900);
    const webpPath = path.join(outDir, `${base}.webp`);
    await sharp(Buffer.from(svg), { density: 96 })
      .resize(w, h)
      .webp({ quality: 82, effort: 6 })
      .toFile(webpPath);
    if (img.alsoSvg) await fs.writeFile(path.join(outDir, `${base}.svg`), svg);
    const kb = ((await fs.stat(webpPath)).size / 1024).toFixed(0);
    rows.push({ ...img, base, w, h, kb });
    console.log(`${page.slug}/${base}.webp  ${w}x${h}  ${kb} KB`);
  }
  // Placement guide next to the page content
  const md = [
    `# Images — ${page.slug}`,
    "",
    "Original diagrams generated by `scripts/content-images/generate.mjs` (re-run to regenerate).",
    "All images are WebP with fixed dimensions. Set `width`/`height` to avoid layout shift. Lazy-load everything except the hero.",
    "",
    "| # | Placement | File | Size | Alt text |",
    "|---|---|---|---|---|",
    ...rows.map(
      (r, i) =>
        `| ${i + 1} | ${r.placement} | \`/images/${page.slug}/${r.base}.webp\`${r.alsoSvg ? ` (+ .svg)` : ""} | ${r.w}×${r.h}, ${r.kb} KB | ${r.alt} |`,
    ),
    "",
    "## Ready-to-paste markup",
    "",
    ...rows.flatMap((r, i) => [
      `**${i + 1}. ${r.placement}**`,
      "",
      "```html",
      r.og
        ? `<meta property="og:image" content="https://clickmastersblockchaintechnologies.com/images/${page.slug}/${r.base}.webp" />\n<meta property="og:image:width" content="${r.w}" />\n<meta property="og:image:height" content="${r.h}" />\n<meta property="og:image:alt" content="${r.alt}" />`
        : `<img src="/images/${page.slug}/${r.base}.webp" alt="${r.alt}" width="${r.w}" height="${r.h}"${i === 0 ? ` fetchpriority="high"` : ` loading="lazy" decoding="async"`} />`,
      "```",
      "",
    ]),
  ].join("\n");
  await fs.writeFile(
    path.join(root, "content", page.contentDir, "10-images.md"),
    md,
  );
}
